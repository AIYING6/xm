def build() -> Path:
    parent = PARENT.read_text(encoding="utf-8")
    evidence = EVIDENCE.read_text(encoding="utf-8")
    intro = span(evidence, "# ", "## 2 相关工作")
    technical = span(parent, "## 2 相关工作", "## 5 实验协议")
    result_to_conclusion = span(evidence, "## 6 双 cohort 受控结果", "## 附录A")
    # Tables 2--4 are restored above from the original long-form protocol;
    # shift evidence tables without changing their values or narrative scope.
    result_to_conclusion = (
        result_to_conclusion.replace("表5", "表10")
        .replace("表4", "表9")
        .replace("表3", "表7")
        .replace("表2", "表6")
    )
    # The long-form additions are deliberately inserted at their logical
    # result locations rather than appended as an afterthought.  This retains
    # the parent manuscript's narrative density while keeping every numeric
    # claim on the final A/B evidence contract.
    result_intro, result_tail = RESULTS_EXPANSION.split("### 6.3a ", 1)
    result_63, result_tail = result_tail.split("### 6.4a ", 1)
    result_64, result_65 = result_tail.split("### 6.5a ", 1)
    result_to_conclusion = result_to_conclusion.replace(
        "### 6.1 两个冻结 cohort 中均观察到更高的扰动任务回报",
        result_intro + "### 6.1 两个冻结 cohort 中均观察到更高的扰动任务回报",
    )
